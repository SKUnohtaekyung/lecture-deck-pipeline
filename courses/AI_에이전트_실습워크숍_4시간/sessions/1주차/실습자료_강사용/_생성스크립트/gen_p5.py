def _read(path):
    with open(path, encoding='utf-8', newline=None) as f:
        return f.read()


def _split_kit(html):
    """영상도구을 (앞 · 장면 데이터 구간 · 뒤)로 나눈다. 구획 표시는 정확히 한 번씩만 있어야 한다."""
    assert html.count(MARK_S) == 1 and html.count(MARK_E) == 1, '여기만 고칩니다 구획 표시가 한 쌍이 아니다'
    a = html.index(MARK_S) + len(MARK_S)
    b = html.index(MARK_E)
    assert a < b
    return html[:a], html[a:b], html[b:]


def _frame_span(html):
    """재생기 스크립트(KIT_SUM 줄이 든 script 블록)의 글자 범위."""
    i = html.index("var KIT_SUM = '';")
    a = html.rfind('<script>', 0, i) + len('<script>')
    return a, html.index('</script>', i)


def _fnv(text):
    """브라우저의 kitHash와 같은 값(FNV-1a 32비트, UTF-16 글자 단위)."""
    x = 2166136261
    raw = text.encode('utf-16-le')
    for k in range(0, len(raw), 2):
        x ^= raw[k] | (raw[k + 1] << 8)
        x = (x * 16777619) & 0xFFFFFFFF
    return '%08x' % x


def write_kit():
    """참가자 폴더에 영상도구.html을, 강사용 완성 예시 템플릿(templates/p5.html)을 만든다. 두 파일은 장면 데이터 구간만 다르다.
    재생기 스크립트의 해시를 KIT_SUM에 넣어, 틀 코드가 고쳐졌는지 점검 패널(⑫)이 알아보게 한다."""
    kit = _read(KIT_SRC)
    a, b = _frame_span(kit)
    kit = kit[:a] + kit[a:b].replace("var KIT_SUM = '';", "var KIT_SUM = '%s';" % _fnv(kit[a:b]), 1) + kit[b:]
    head, _data, tail = _split_kit(kit)
    write_text(KIT_OUT, kit)
    if os.path.exists(OLD_KIT_OUT):
        os.remove(OLD_KIT_OUT)
    write_text(EXAMPLE_TPL, head + EXAMPLE_DATA + tail)
    write_text(EX1_OUT, head + EXAMPLE_DATA + tail)
    write_text(EX2_OUT, head + EXAMPLE2_DATA + tail)
    ex_head, _d2, ex_tail = _split_kit(_read(EXAMPLE_TPL))
    assert (ex_head, ex_tail) == (head, tail), '완성 예시의 틀 코드가 영상도구과 다르다'


