def pick(pairs):
    total = sum(w for _, w in pairs)
    r = random.uniform(0, total)
    for v, w in pairs:
        r -= w
        if r <= 0:
            return v
    return pairs[-1][0]


def build_orders():
    orders, n = [], 0
    for d in range(WEEKS * 7):
        day = START + dt.timedelta(days=d)
        week = d // 7 + 1
        base = 9 + week * 0.35 + (3 if day.weekday() >= 5 else 0)
        if dt.date(2026, 2, 14) <= day <= dt.date(2026, 2, 18):      # 설 연휴 배송 휴무
            base *= 0.45
        count = max(3, int(random.gauss(base, 1.8)))
        plan = [pick(CHANNELS) for _ in range(count)] + ['라이브방송'] * LIVE_DAYS.get(day, 0)
        for ch in plan:
            pool = [(p, p[5]) for p in PRODUCTS if not (p[0] == STOCKOUT[0] and STOCKOUT[1] <= day <= STOCKOUT[2])]
            if ch == '라이브방송':
                pool = [(p, w * (6 if p[0] in ('K-101', 'K-103', 'L-404') else 1)) for p, w in pool]
            p = pick(pool)
            qty = random.choices([1, 2, 3, 4], [62, 25, 9, 4])[0]
            rate = {'자사몰': random.choice([0, 0, 0, 0.05, 0.1]), '오픈마켓': random.choice([0, 0.05, 0.1]),
                    '소셜커머스': random.choice([0.1, 0.15]), '라이브방송': 0.2}[ch]
            disc = int(round(p[3] * qty * rate / 100.0)) * 100
            n += 1
            orders.append([day.isoformat(), 'H%05d' % (26000 + n), ch, p[0], p[1], p[2], qty, p[3], disc,
                           p[3] * qty - disc, pick(REGIONS), random.choices(['신규', '재구매'], [58, 42])[0]])
    return orders


