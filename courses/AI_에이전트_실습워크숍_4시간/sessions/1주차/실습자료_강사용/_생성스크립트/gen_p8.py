# ── 만들다 멈추는 검사: 답글의 기한 · 금액이 응대기준과 같은지, 함정 답이 맞는지 ──────────────────
TOKEN = re.compile(r'(영업일\s*)?(\d[\d,]*)\s*(원|일)')
BANNED = ['소중한', '최선을 다', '보답', '!', '전액 환불', '쿠폰을 드', '쿠폰을 보내', '쿠폰을 지급', '적립금을 드', '보상해 드']


def tokens(s):
    return {('영업일 ' if m.group(1) else '') + m.group(2) + m.group(3) for m in TOKEN.finditer(s)}


def days_between(r):
    return (date.fromisoformat(r['wrote']) - date.fromisoformat(r['got'])).days


def verify():
    allowed_doc = tokens(STANDARD)
    for r in REVIEWS:
        r['days'] = days_between(r)
        extra = tokens(r['text']) | {'%d일' % r['days']}
        bad = tokens(full_reply(r)) - allowed_doc - extra
